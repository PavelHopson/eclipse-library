// Isolated headless Edge. No real profile, external browsing or installs.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const origin = 'http://127.0.0.1:4216';
const out = path.resolve(__dirname, '../reports/library-mascot');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const errors = [], blocked = [], checks = [];
  await context.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin === origin || url.protocol === 'data:') return route.continue();
    blocked.push(url.origin); return route.abort();
  });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  const mark = name => checks.push(name);
  const open = async (preview = true) => {
    await page.goto(origin + (preview ? '/?mascot=preview' : '/'));
    await page.waitForSelector('.card');
    if (preview) await page.waitForSelector('#libraryMascot');
  };
  const state = async name => page.waitForFunction(n => document.querySelector('#libraryMascot')?.dataset.state === n, name);
  const search = async text => {
    await page.locator('#search').fill(text);
    await page.waitForTimeout(220);
  };
  try {
    await open();
    await page.locator('#libraryMascot').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'desktop.png') });
    await page.locator('.library-mascot-pet').focus();
    await page.keyboard.press('Enter'); await state('tap');
    const frames = await page.locator('.library-mascot-art').evaluate(el => el.getAnimations()[0]?.effect.getKeyframes());
    assert.ok(frames?.length === 2); assert.ok(frames.every(f => 'opacity' in f));
    await page.locator('.library-mascot-art').evaluate(el => { const a = el.getAnimations()[0]; a.pause(); a.currentTime = 90; });
    await page.screenshot({ path: path.join(out, 'motion-mid.png') });
    mark('keyboard Enter, finite opacity animation, mid-frame screenshot');
    await page.keyboard.press('Space'); await state('tap'); mark('keyboard Space');
    await page.locator('[data-mascot-static]').click();
    await page.locator('.library-mascot-pet').click();
    assert.equal(await page.locator('.library-mascot-art').evaluate(el => el.getAnimations().length), 0);
    mark('manual static mode');
    await page.locator('[data-mascot-hide]').click();
    assert.equal(await page.locator('.library-mascot-body').isVisible(), false);
    assert.equal(await page.locator('.library-mascot-restore').evaluate(el => el === document.activeElement), true);
    await page.reload(); await page.waitForSelector('.library-mascot-restore');
    assert.equal(await page.locator('.library-mascot-body').isVisible(), false);
    await page.locator('.library-mascot-restore').press('Enter');
    assert.equal(await page.locator('.library-mascot-pet').evaluate(el => el === document.activeElement), true);
    mark('hide/return, focus restoration, preferences survive reload');
    await search('zzzz-no-match-028'); await state('empty');
    assert.match(await page.locator('#resultcount').innerText(), /^0 /);
    await search('Anti-Miner'); await state('found');
    assert.ok(new URL(page.url()).searchParams.get('mascot') === 'preview');
    const guideCard = page.locator('.card[data-item-id="anti-miner-github-com"]');
    await guideCard.locator('.card-title a').click();
    await page.waitForSelector('#itemView:not([hidden])');
    const guide = page.locator('#itemView a[href^="#guide/"]').first();
    await guide.click();
    await page.waitForSelector('#guideView:not([hidden])');
    await page.waitForFunction(() => document.querySelector('#guideBody').innerText.length > 200);
    mark('real search: empty/found → card → guide with mascot');
    await open(); await page.locator('[data-mascot-hide]').click();
    await search('Anti-Miner');
    await page.locator('.card[data-item-id="anti-miner-github-com"] .card-title a').click();
    await page.locator('#itemView a[href^="#guide/"]').first().click();
    await page.waitForFunction(() => document.querySelector('#guideBody').innerText.length > 200);
    mark('real search → guide with mascot hidden');
    await open(false); assert.equal(await page.locator('#libraryMascot').count(), 0);
    mark('default page has no mascot or mascot stylesheet');
    assert.equal(await page.locator('link[href*="library-mascot.css"]').count(), 0);
    await context.clearCookies();
    await page.evaluate(() => localStorage.removeItem('eclipse-library:mascot-preview:v1'));
    await open();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.waitForFunction(() => document.querySelector('[data-mascot-static]').disabled);
    await page.locator('.library-mascot-pet').click();
    assert.equal(await page.locator('.library-mascot-art').evaluate(el => el.getAnimations().length), 0);
    assert.ok(await page.locator('[data-mascot-static]').isDisabled());
    await page.screenshot({ path: path.join(out, 'reduced-motion.png') });
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.waitForFunction(() => !document.querySelector('[data-mascot-static]').disabled);
    mark('live OS reduced-motion change, static screenshot');
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      await page.locator('#libraryMascot').scrollIntoViewIfNeeded();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.screenshot({ path: path.join(out, `mobile-${width}.png`) });
    }
    mark('320/390 layout without horizontal overflow');
    const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
    await touch.route('**/*', r => new URL(r.request().url()).origin === origin ? r.continue() : r.abort());
    const phone = await touch.newPage();
    await phone.goto(origin + '/?mascot=preview');
    await phone.locator('.library-mascot-pet').tap();
    assert.equal(await phone.locator('#libraryMascot').getAttribute('data-state'), 'tap');
    await phone.locator('[data-mascot-hide]').tap();
    await phone.locator('.library-mascot-restore').tap();
    await phone.locator('#heroSearch').fill('LocalSend');
    await phone.locator('#heroCommand button[type="submit"]').tap();
    await phone.waitForFunction(() => document.querySelector('#libraryMascot').dataset.state === 'found');
    await touch.close(); mark('touch tap/hide/restore and hero search');
    const broken = await context.newPage();
    await broken.route('**/assets/mascots/library-list-v0.1.0/*.svg', r => r.abort());
    await broken.goto(origin + '/?mascot=preview');
    await broken.waitForSelector('.library-mascot-fallback:not([hidden])');
    await broken.locator('.library-mascot-pet').click();
    assert.match(await broken.locator('.library-mascot-message').innerText(), /Мур/);
    await broken.close(); mark('missing art: one fallback then text, controls remain usable');
    assert.deepEqual(errors, []);
    const sizes = Object.fromEntries(['library-mascot.mjs', 'library-mascot.css'].map(f => [f, fs.statSync(path.resolve(__dirname, '../web', f)).size]));
    const report = { browser: browser.version(), checks, errors, blocked: [...new Set(blocked)], sizes, finalAssets: false, production: false };
    fs.writeFileSync(path.join(out, 'qa.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });

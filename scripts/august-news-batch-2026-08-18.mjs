const sourceText = await readFile(catalogUrl, 'utf8');
const newline = sourceText.includes('\r\n') ? '\r\n' : '\n';
const catalog = JSON.parse(sourceText);
const byId = new Map(catalog.items.map((item) => [item.id, item]));
const canonical = (value) => {
  const url = new URL(value);
  url.hash = '';
  url.hostname = url.hostname.toLowerCase().replace(/^www\./, '');
  url.pathname = url.pathname.replace(/\/+$/, '') || '/';
  return url.toString().replace(/\/$/, '');
};
const urls = new Map(catalog.items.map((item) => [canonical(item.url), item.id]));

const missingDuplicates = [...duplicateIds].filter((id) => !byId.has(id));
if (missingDuplicates.length) throw new Error(`Expected duplicate records are missing: ${missingDuplicates.join(', ')}`);

for (const record of records) {
  if (byId.has(record.id)) throw new Error(`Record id already exists: ${record.id}`);
  const key = canonical(record.url);
  if (urls.has(key)) throw new Error(`Record URL already exists as ${urls.get(key)}: ${record.url}`);
  catalog.items.push(record);
  byId.set(record.id, record);
  urls.set(key, record.id);
}

catalog.totals.items = catalog.items.length;
const output = JSON.stringify(catalog, null, 2).replace(/\n/g, newline) + newline;
